-- ============================================================================
--  SGCE - Sistema de Gestión de Convivencia Educativos
--  Script de creación de base de datos (eliminación + creación de tablas)
--  Motor: PostgreSQL 13 o superior
--  Basado en el diagrama entidad-relación "SGCE_bd.png"
--
--  Convenciones
--    * Nombres en minúsculas y snake_case (PostgreSQL pliega los identificadores
--      sin comillas a minúsculas).
--    * Claves primarias enteras: IDENTITY (equivalente moderno a SERIAL).
--    * Claves primarias UUID: tipo nativo uuid + DEFAULT gen_random_uuid().
--    * "string" del diagrama se implementa como varchar (no es un tipo SQL).
--    * Todo timestamp por defecto es CURRENT_TIMESTAMP (hora local del servidor).
--    * Las tablas se eliminan en orden inverso a las dependencias.
-- ============================================================================

BEGIN;

-- ============================================================================
--  1. ELIMINACIÓN DE TABLAS (orden inverso a las dependencias)
-- ============================================================================
DROP TABLE IF EXISTS consulta_logs           CASCADE;
DROP TABLE IF EXISTS consultas               CASCADE;
DROP TABLE IF EXISTS cita_participantes      CASCADE;
DROP TABLE IF EXISTS citas                   CASCADE;
DROP TABLE IF EXISTS solicitudes_agendamiento CASCADE;
DROP TABLE IF EXISTS publicacion_audiencias  CASCADE;
DROP TABLE IF EXISTS publicaciones           CASCADE;
DROP TABLE IF EXISTS estudiante_detalles     CASCADE;
DROP TABLE IF EXISTS reportes                CASCADE;
DROP TABLE IF EXISTS caso_participantes      CASCADE;
DROP TABLE IF EXISTS caso_archivos           CASCADE;
DROP TABLE IF EXISTS archivos                CASCADE;
DROP TABLE IF EXISTS casos                   CASCADE;
DROP TABLE IF EXISTS notificaciones          CASCADE;
DROP TABLE IF EXISTS usuarios                CASCADE;
DROP TABLE IF EXISTS cursos                  CASCADE;
DROP TABLE IF EXISTS roles                   CASCADE;
DROP TABLE IF EXISTS departamentos           CASCADE;

-- ============================================================================
--  2. TABLAS CATÁLOGO (sin dependencias)
-- ============================================================================

-- Departamentos de la institución. Se usan para asignar usuarios y casos.
CREATE TABLE departamentos (
    id      integer      GENERATED BY DEFAULT AS IDENTITY,
    nombre  varchar(150) NOT NULL,
    CONSTRAINT pk_departamentos      PRIMARY KEY (id),
    CONSTRAINT uq_departamentos_nombre UNIQUE (nombre)
);

-- Roles del sistema (administrador, docente, apoderado, estudiante, etc.).
CREATE TABLE roles (
    id      integer      GENERATED BY DEFAULT AS IDENTITY,
    nombre  varchar(100) NOT NULL,
    CONSTRAINT pk_roles        PRIMARY KEY (id),
    CONSTRAINT uq_roles_nombre UNIQUE (nombre)
);

-- Cursos / niveles educativos.
CREATE TABLE cursos (
    id        integer      GENERATED BY DEFAULT AS IDENTITY,
    categoria varchar(100) NOT NULL,
    nivel     varchar(50)  NOT NULL,
    CONSTRAINT pk_cursos             PRIMARY KEY (id),
    CONSTRAINT uq_cursos_cat_nivel   UNIQUE (categoria, nivel)
);

-- ============================================================================
--  3. USUARIOS Y NOTIFICACIONES
-- ============================================================================

-- Usuario único del sistema: estudiantes, apoderados, docentes y funcionarios.
CREATE TABLE usuarios (
    id              uuid         NOT NULL DEFAULT gen_random_uuid(),
    rol_id          integer      NOT NULL,
    departamento_id integer      NOT NULL,
    nombre          varchar(100) NOT NULL,
    apellido1       varchar(100) NOT NULL,
    apellido2       varchar(100),
    rut             varchar(15)  NOT NULL,
    correo          varchar(150) NOT NULL,
    constrasenia    varchar(255) DEFAULT NULL,
    fecha_nacimiento date,
    CONSTRAINT pk_usuarios              PRIMARY KEY (id),
    CONSTRAINT uq_usuarios_rut          UNIQUE (rut),
    CONSTRAINT uq_usuarios_correo       UNIQUE (correo),
    CONSTRAINT fk_usuarios_rol          FOREIGN KEY (rol_id)
        REFERENCES roles (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_usuarios_departamento FOREIGN KEY (departamento_id)
        REFERENCES departamentos (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Notificaciones enviadas a un usuario (correo y/o sistema).
CREATE TABLE notificaciones (
    id                integer      GENERATED BY DEFAULT AS IDENTITY,
    receptor_id       uuid         NOT NULL,
    correo_receptor   varchar(150),
    tipo_notificacion varchar(50)  NOT NULL,
    titulo            varchar(200) NOT NULL,
    mensaje           varchar(1000),
    leido             boolean      NOT NULL DEFAULT false,
    estado_envio      varchar(30)  NOT NULL DEFAULT 'pendiente',
    fecha_creacion    timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_notificaciones        PRIMARY KEY (id),
    CONSTRAINT fk_notificaciones_receptor FOREIGN KEY (receptor_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ============================================================================
--  4. CASOS, ARCHIVOS Y PARTICIPANTES
-- ============================================================================

-- Casos o incidencias gestionadas por un departamento y un encargado.
CREATE TABLE casos (
    id              integer      GENERATED BY DEFAULT AS IDENTITY,
    departamento_id integer      NOT NULL,
    encargado_id    uuid,
    tipo_caso       varchar(50)  NOT NULL,
    titulo          varchar(200) NOT NULL,
    descripcion     text,
    prioridad       varchar(20)  NOT NULL DEFAULT 'media',
    estado          varchar(30)  NOT NULL DEFAULT 'abierto',
    fecha_creacion  timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_casos                 PRIMARY KEY (id),
    CONSTRAINT fk_casos_departamento    FOREIGN KEY (departamento_id)
        REFERENCES departamentos (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_casos_encargado       FOREIGN KEY (encargado_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- Archivos cargados al sistema (documentos, imágenes, adjuntos).
CREATE TABLE archivos (
    id             uuid         NOT NULL DEFAULT gen_random_uuid(),
    nombre         varchar(255) NOT NULL,
    url_archivo    varchar(500) NOT NULL,
    tipo_archivo   varchar(50),
    creador_id     uuid,
    fecha_creacion timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_archivos          PRIMARY KEY (id),
    CONSTRAINT fk_archivos_creador  FOREIGN KEY (creador_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- Relación N:M entre casos y archivos.
-- NOTA: el diagrama rotula caso_id como uuid; se usa integer para que coincida
--       con casos.id (las claves foráneas deben compartir el tipo).
CREATE TABLE caso_archivos (
    caso_id    integer NOT NULL,
    archivo_id uuid    NOT NULL,
    CONSTRAINT pk_caso_archivos         PRIMARY KEY (caso_id, archivo_id),
    CONSTRAINT fk_caso_archivos_caso    FOREIGN KEY (caso_id)
        REFERENCES casos (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_caso_archivos_archivo FOREIGN KEY (archivo_id)
        REFERENCES archivos (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Relación N:M entre casos y usuarios participantes (con su rol en el caso).
CREATE TABLE caso_participantes (
    caso_id     integer     NOT NULL,
    usuario_id  uuid        NOT NULL,
    rol_en_caso varchar(50),
    CONSTRAINT pk_caso_participantes         PRIMARY KEY (caso_id, usuario_id),
    CONSTRAINT fk_caso_participantes_caso    FOREIGN KEY (caso_id)
        REFERENCES casos (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_caso_participantes_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Reportes levantados por un usuario (emisor) sobre un tema o caso.
CREATE TABLE reportes (
    id             integer     GENERATED BY DEFAULT AS IDENTITY,
    tipo           varchar(50) NOT NULL,
    emisor_id      uuid        NOT NULL,
    gravedad       varchar(20),
    descripcion    text,
    estado         varchar(30) NOT NULL DEFAULT 'nuevo',
    fecha_creacion timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_reportes          PRIMARY KEY (id),
    CONSTRAINT fk_reportes_emisor   FOREIGN KEY (emisor_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ============================================================================
--  5. DATOS ACADÉMICOS DEL ESTUDIANTE
-- ============================================================================

-- Extensión 1:1 de usuarios para quienes son estudiantes.
CREATE TABLE estudiante_detalles (
    id                uuid        NOT NULL,
    apoderado_id      uuid        NOT NULL,
    vinculo_apoderado varchar(50),
    curso_id          integer     NOT NULL,
    CONSTRAINT pk_estudiante_detalles             PRIMARY KEY (id),
    CONSTRAINT fk_estudiante_detalles_usuario     FOREIGN KEY (id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_estudiante_detalles_apoderado   FOREIGN KEY (apoderado_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_estudiante_detalles_curso       FOREIGN KEY (curso_id)
        REFERENCES cursos (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ============================================================================
--  6. PUBLICACIONES Y AUDIENCIAS
-- ============================================================================

-- Publicaciones del muro institucional.
CREATE TABLE publicaciones (
    id                 uuid         NOT NULL DEFAULT gen_random_uuid(),
    autor_id           uuid         NOT NULL,
    titulo             varchar(200) NOT NULL,
    contenido          text,
    imagen_url         varchar(500),
    categoria          varchar(50),
    publicado          boolean      NOT NULL DEFAULT false,
    fecha_creacion     timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion timestamp,
    CONSTRAINT pk_publicaciones        PRIMARY KEY (id),
    CONSTRAINT fk_publicaciones_autor  FOREIGN KEY (autor_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Relación N:M: a qué roles está dirigida cada publicación.
CREATE TABLE publicacion_audiencias (
    publicacion_id   uuid    NOT NULL,
    rol_objetivo_id  integer NOT NULL,
    CONSTRAINT pk_publicacion_audiencias          PRIMARY KEY (publicacion_id, rol_objetivo_id),
    CONSTRAINT fk_publicacion_audiencias_pub      FOREIGN KEY (publicacion_id)
        REFERENCES publicaciones (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_publicacion_audiencias_rol      FOREIGN KEY (rol_objetivo_id)
        REFERENCES roles (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ============================================================================
--  7. AGENDAMIENTO DE CITAS
-- ============================================================================

-- Solicitudes de agendamiento realizadas por un usuario solicitante.
CREATE TABLE solicitudes_agendamiento (
    id                uuid        NOT NULL DEFAULT gen_random_uuid(),
    solicitante_id    uuid        NOT NULL,
    tipo_solicitud    varchar(50) NOT NULL,
    solicitud_inicial uuid,
    motivo_detallado  text,
    gravedad          varchar(20),
    estado            varchar(30) NOT NULL DEFAULT 'pendiente',
    modalidad         varchar(20),
    fecha_creacion    timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_solicitudes_agendamiento            PRIMARY KEY (id),
    CONSTRAINT fk_solicitudes_agendamiento_solicitante FOREIGN KEY (solicitante_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Citas generadas a partir de una solicitud de agendamiento.
CREATE TABLE citas (
    id           integer     GENERATED BY DEFAULT AS IDENTITY,
    solicitud_id uuid        NOT NULL,
    modalidad    varchar(20),
    url_reunion  varchar(500),
    hora_inicio  timestamp   NOT NULL,
    hora_fin     timestamp   NOT NULL,
    estado       varchar(30) NOT NULL DEFAULT 'programada',
    CONSTRAINT pk_citas              PRIMARY KEY (id),
    CONSTRAINT fk_citas_solicitud    FOREIGN KEY (solicitud_id)
        REFERENCES solicitudes_agendamiento (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_citas_horas        CHECK (hora_fin > hora_inicio)
);

-- Relación N:M entre citas y usuarios asistentes.
CREATE TABLE cita_participantes (
    cita_id     integer     NOT NULL,
    usuario_id  uuid        NOT NULL,
    rol_en_cita varchar(50),
    asiste      boolean     NOT NULL DEFAULT false,
    CONSTRAINT pk_cita_participantes         PRIMARY KEY (cita_id, usuario_id),
    CONSTRAINT fk_cita_participantes_cita    FOREIGN KEY (cita_id)
        REFERENCES citas (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_cita_participantes_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ============================================================================
--  8. CONSULTAS Y SU BITÁCORA
-- ============================================================================

-- Consultas / tickets de soporte abiertos por un usuario según su rol.
CREATE TABLE consultas (
    id             uuid        NOT NULL DEFAULT gen_random_uuid(),
    user_id        uuid        NOT NULL,
    rol_usuario_id integer     NOT NULL,
    severidad      varchar(20),
    detalles       text,
    fecha_creacion timestamp   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_consultas               PRIMARY KEY (id),
    CONSTRAINT fk_consultas_usuario       FOREIGN KEY (user_id)
        REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_consultas_rol           FOREIGN KEY (rol_usuario_id)
        REFERENCES roles (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Mensajes/respuestas de seguimiento de cada consulta.
-- Cada entrada de la bitácora se identifica por su propio id (uuid); consulta_id
-- es la clave foránea que la asocia al ticket correspondiente.
CREATE TABLE consulta_logs (
    id             uuid         NOT NULL DEFAULT gen_random_uuid(),
    consulta_id    uuid         NOT NULL,
    mensaje        text,
    adjunto        varchar(500),
    respuesta      text,
    fecha_creacion timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_consulta_logs          PRIMARY KEY (id),
    CONSTRAINT fk_consulta_logs_consulta FOREIGN KEY (consulta_id)
        REFERENCES consultas (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ============================================================================
--  9. ÍNDICES SOBRE CLAVES FORÁNEAS
--     (PostgreSQL no indexa automáticamente las FK; se agregan para las
--      columnas que no quedan cubiertas por una PK o restricción UNIQUE)
-- ============================================================================
CREATE INDEX idx_usuarios_rol               ON usuarios (rol_id);
CREATE INDEX idx_usuarios_departamento      ON usuarios (departamento_id);
CREATE INDEX idx_casos_departamento         ON casos (departamento_id);
CREATE INDEX idx_casos_encargado            ON casos (encargado_id);
CREATE INDEX idx_archivos_creador           ON archivos (creador_id);
CREATE INDEX idx_caso_archivos_archivo      ON caso_archivos (archivo_id);
CREATE INDEX idx_caso_participantes_usuario ON caso_participantes (usuario_id);
CREATE INDEX idx_reportes_emisor            ON reportes (emisor_id);
CREATE INDEX idx_estudiante_detalles_apod   ON estudiante_detalles (apoderado_id);
CREATE INDEX idx_estudiante_detalles_curso  ON estudiante_detalles (curso_id);
CREATE INDEX idx_publicaciones_autor        ON publicaciones (autor_id);
CREATE INDEX idx_publicacion_audiencias_rol ON publicacion_audiencias (rol_objetivo_id);
CREATE INDEX idx_solicitudes_solicitante    ON solicitudes_agendamiento (solicitante_id);
CREATE INDEX idx_citas_solicitud            ON citas (solicitud_id);
CREATE INDEX idx_cita_participantes_usuario ON cita_participantes (usuario_id);
CREATE INDEX idx_consultas_usuario          ON consultas (user_id);
CREATE INDEX idx_consultas_rol              ON consultas (rol_usuario_id);
CREATE INDEX idx_consulta_logs_consulta     ON consulta_logs (consulta_id);

-- ============================================================================
-- 10. COMENTARIOS DE TABLAS
-- ============================================================================
COMMENT ON TABLE departamentos            IS 'Departamentos de la institución';
COMMENT ON TABLE roles                    IS 'Roles del sistema';
COMMENT ON TABLE cursos                   IS 'Cursos y niveles educativos';
COMMENT ON TABLE usuarios                 IS 'Usuarios del sistema (estudiantes, apoderados, funcionarios)';
COMMENT ON TABLE notificaciones           IS 'Notificaciones enviadas a los usuarios';
COMMENT ON TABLE casos                    IS 'Casos o incidencias gestionadas';
COMMENT ON TABLE archivos                 IS 'Archivos cargados al sistema';
COMMENT ON TABLE caso_archivos            IS 'Archivos adjuntos a cada caso';
COMMENT ON TABLE caso_participantes       IS 'Usuarios involucrados en un caso';
COMMENT ON TABLE reportes                 IS 'Reportes levantados por usuarios';
COMMENT ON TABLE estudiante_detalles      IS 'Datos académicos del estudiante (1:1 con usuarios)';
COMMENT ON TABLE publicaciones            IS 'Publicaciones del muro institucional';
COMMENT ON TABLE publicacion_audiencias   IS 'Roles a los que se dirige una publicación';
COMMENT ON TABLE solicitudes_agendamiento IS 'Solicitudes de agendamiento de reuniones';
COMMENT ON TABLE citas                    IS 'Citas agendadas';
COMMENT ON TABLE cita_participantes       IS 'Participantes de cada cita';
COMMENT ON TABLE consultas                IS 'Consultas o tickets de soporte';
COMMENT ON TABLE consulta_logs            IS 'Mensajes de seguimiento de cada consulta';

COMMIT;

